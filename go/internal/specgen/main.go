// Command specgen writes spec_data.go from ../spec/rules.json, so the module carries the
// spec without reaching outside its own directory. Run with `go generate` in go/.
package main

import (
	"fmt"
	"os"
	"strconv"
)

func main() {
	data, err := os.ReadFile("../spec/rules.json")
	if err != nil {
		fmt.Fprintln(os.Stderr, "specgen:", err)
		os.Exit(1)
	}
	out := "// Code generated by internal/specgen from ../spec/rules.json. DO NOT EDIT.\n\n" +
		"package slopdam\n\n" +
		"const rulesJSON = " + strconv.Quote(string(data)) + "\n"
	if err := os.WriteFile("spec_data.go", []byte(out), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "specgen:", err)
		os.Exit(1)
	}
}
